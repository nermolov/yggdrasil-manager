// DocumentAM is a minimal valid Automerge v2 binary document fixture.
// It starts with the Automerge magic bytes (0x85 0x6f 0x4a 0x83), followed by
// a varint-encoded version byte (0x02), then a minimal empty-document payload.
// This is equivalent to the canonical empty-document encoding for Automerge 2.x.
//
// The fixture is used as a stable input for WASM-module benchmarks so that
// memory measurements are not skewed by I/O or document loading time.
var DocumentAM = []byte{
	0x85, 0x6f, 0x4a, 0x83, // Automerge magic bytes
	0x02, // version varint (2)
	0x95, // remaining header byte
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x00, 0x00,
}
